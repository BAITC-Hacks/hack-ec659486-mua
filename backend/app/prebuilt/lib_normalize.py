#!/usr/bin/env python3
"""lib_normalize.py — детерминированная нормализация атомарной функции.

Даёт быстрый базовый слой аналитического ядра (плана §«Аналитическое ядро»):
  • work_nature(text)  → Разработка | Методология | Эксплуатация
  • signature(text)    → (verb_class, object_head) для лексического блокинга дедупа

Правила сознательно эвристические (~80% точности); неоднозначные случаи
(особенно вспомогательные глаголы «обеспечивать/осуществлять») уточняет LLM Pass B.
Принцип, сохраняемый системой: АВТОРСТВО единого метода = Методология; СОЗДАНИЕ
нового артефакта/системы = Разработка; КОНТРОЛЬ/ВЕДЕНИЕ существующего = Эксплуатация.
"""

from __future__ import annotations

import re

# вспомогательные («прозрачные») глаголы — делегируют действие следующему слову
AUX = re.compile(
    r"^(обеспеч\w*|осуществл\w*|организ\w*|координир\w*|проводит\w*|проведени\w*|"
    r"принима\w*\s+участие\s+в|участвова\w*\s+в|участ\w*\s+в|реализ\w*)\s+",
    re.IGNORECASE,
)

# ── классы глаголов (по основе ведущего слова) ──────────────────────────────
CONTROL = re.compile(
    r"^(контрол|монитор|проверк|проверя|надзор|уч[еёт]т|учит|вед[еёy]|ведени|"
    r"регистрац|регистр|сопровожд|обработ|оформл|актуализ|анализ|сбор|собир|"
    r"выдач|выда|при[её]м|хранен|хран|размещ|заполн|исполн|соблюд|информир|"
    r"отч[еёт]т|отчит|рассмотр|обновлен|поддержани|поддержива|примен|использ|"
    r"начислен|начисл|расч[еёт]т|выплат|сверк|инвентар|архивир)",
    re.IGNORECASE,
)

CREATE = re.compile(
    r"^(разработ|разрабат|создани|созда[её]|проектир|формировани|формиру|"
    r"составлени|составл|подготовк|подготов|внедрени|внедр|запуск|инициир|"
    r"нормировани|нормир|экспертиз|моделир|автоматизац)",
    re.IGNORECASE,
)

# ── объекты ─────────────────────────────────────────────────────────────────
# артефакт-правило → методология (авторство нормы для других)
METHOD_OBJ = re.compile(
    r"(регламент|стандарт\w*|методолог|методик|политик|положени\w*\s+о\b|"
    r"инструкци|норматив|критери|номенклатур\s+дел|бизнес-процесс|"
    r"паспорт\w*\s+процесс|типов\w+\s+форм|свок|смк|"
    r"методическ\w*\s+(?:рекоменд|обеспечен|сопровожд|материал))",
    re.IGNORECASE,
)

# новый артефакт/система → разработка
DEV_OBJ = re.compile(
    r"(систем\w*|сервис\w*|стратеги\w*|проект\w*|платформ\w*|продукт\w*|концепци\w*|"
    r"модул\w*|приложени\w*|сайт\w*|портал\w*|программн\w*|инструмент\w*|"
    r"кампани\w*|мероприяти\w*\s+нов|дизайн|макет\w*|контент|медиаплан)",
    re.IGNORECASE,
)

WORK_NATURES = ("Разработка", "Методология", "Эксплуатация")


def _head(text: str) -> str:
    t = text.strip().lower()
    # снять вспомогательный глагол, чтобы увидеть настоящее действие
    for _ in range(2):
        m = AUX.match(t)
        if m:
            t = t[m.end() :]
        else:
            break
    return t


# создающий глагол где угодно в тексте (для «обеспечивать разработку…» и фоллбэка)
_CREATE_ANY = re.compile(
    r"\b(разработ\w*|разрабат\w*|создани\w*|созда[её]\w*|проектир\w*|формировани\w*|"
    r"составлени\w*|внедрени\w*|нормировани\w*|экспертиз\w*|актуализаци\w*)",
    re.IGNORECASE,
)
# операционный контроль где угодно (аудит/проверка существующего)
_CONTROL_ANY = re.compile(
    r"\b(аудит\w*|проверк\w*|мониторинг\w*|контрол\w*|надзор\w*)", re.IGNORECASE
)


def work_nature(text: str) -> str:
    t = text.strip().lower()
    head = _head(t)
    has_method = bool(METHOD_OBJ.search(t))
    has_dev = bool(DEV_OBJ.search(t))
    if CONTROL.match(head):
        return "Эксплуатация"  # ведение/контроль/учёт существующего
    if CREATE.match(head):
        if has_method:
            return "Методология"  # авторство нормы (разработка регламента)
        if has_dev:
            return "Разработка"  # создание новой системы/стратегии/проекта
        return "Эксплуатация"  # «подготовка отчёта/корреспонденции» — рутина
    # фоллбэк: методология только при наличии АВТОРСКОГО глагола и без операц.контроля
    if has_method and _CREATE_ANY.search(t) and not _CONTROL_ANY.search(t):
        return "Методология"  # «обеспечивать разработку стандартов»
    if has_dev and _CREATE_ANY.search(t) and not _CONTROL_ANY.search(t):
        return "Разработка"
    return "Эксплуатация"


# ── каноническая сигнатура для лексического блокинга ────────────────────────
_VERB_CLASS = [
    ("МЕТОДОЛОГИЯ", re.compile(r"^(нормир|экспертиз)")),
    ("СОЗДАВАТЬ", CREATE),
    ("КОНТРОЛИРОВАТЬ", re.compile(r"^(контрол|монитор|проверк|проверя|надзор|аудит)")),
    (
        "ВЕСТИ_УЧЁТ",
        re.compile(
            r"^(уч[еёт]т|учит|вед|регистрац|регистр|актуализ|"
            r"обновлен|инвентар|архивир|начисл|расч[еёт]т)"
        ),
    ),
    ("СОГЛАСОВЫВАТЬ", re.compile(r"^(согласов|визир|утвержд|рассмотр|подпис)")),
    ("ОТЧИТЫВАТЬСЯ", re.compile(r"^(отч[еёт]т|отчит|информир|предоставлени\w*\s+отч)")),
    ("ЗАКУПАТЬ", re.compile(r"^(закуп|приобрет|тендер|конкурсн)")),
    ("ОБУЧАТЬ", re.compile(r"^(обуч|консультир|консультац|инструктаж|тренинг|семинар)")),
    ("ОРГАНИЗОВЫВАТЬ", re.compile(r"^(организ|координир|проводит|проведени|обеспеч)")),
    ("ЭКСПЛУАТИРОВАТЬ", re.compile(r"^(обслуж|эксплуатац|ремонт|техническ\w*\s+обслуж)")),
]
_STOP = re.compile(
    r"\b(в|во|и|или|на|по|с|со|для|из|от|до|при|об|о|а|также|том|числе|"
    r"университета|университете|департамента|отдела|подразделения|"
    r"структурных|настоящ\w*|соответствии|рамках|целях|пределах|"
    r"своевременн\w*|качественн\w*|надлежащ\w*)\b",
    re.IGNORECASE,
)


def verb_class(text: str) -> str:
    head = _head(text.strip().lower())
    for name, rx in _VERB_CLASS:
        if rx.match(head):
            return name
    return "ПРОЧЕЕ"


def object_head(text: str, max_words: int = 6) -> str:
    """Грубая лемма-объект: снять ведущее действие, выкинуть стоп-слова, усечь.
    Без морфологии (pymorphy отложен) — годится для exact-блокинга, не для финала."""
    t = _head(text.strip().lower())
    # снять первое слово-действие (verbal noun/инфинитив)
    t = re.sub(r"^[а-яёa-z]+(?:\s+(?:и|или)\s+[а-яёa-z]+)?\s+", "", t, count=1)
    t = re.split(r"[;:(,]", t)[0]  # до первого разделителя
    t = _STOP.sub(" ", t)
    words = [w for w in re.findall(r"[а-яёa-z0-9-]+", t) if len(w) > 2]
    return " ".join(words[:max_words]).strip()


def signature(text: str) -> str:
    return f"{verb_class(text)}|{object_head(text)}"


